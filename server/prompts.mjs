import { label } from './dates.mjs';

const kindLabel = (k) => k;

/** 事実欄（Live の初期指示と、判断モデルの入力の両方で使う） */
export function factsBlock({ today, now, events, lunch, pending, lastAdded, names = [], dashboardError = null }) {
  const lines = [];
  lines.push(`今日: ${today}（${label(today)}） 現在時刻: ${now}`);
  lines.push('');
  if (dashboardError) {
    lines.push('## 注意: 所在ダッシュボードに接続できていない');
    lines.push('予定の読み書きができない。予定を言われたら「いまダッシュボードにつながらないので、あとでもう一度お願いします」と伝える。お弁当の回答は受けてよい。');
    lines.push('');
  }
  lines.push('## 会長の予定（所在ダッシュボードより。先月〜3 か月先。過去の予定は [済]。id は削除に使う）');
  if (events.length === 0) lines.push('（この期間の予定は入っていない）');
  for (const e of events) {
    const span = e.endDate ? `${e.date}〜${e.endDate}` : e.date;
    const done = (e.endDate || e.date) < today ? ' [済]' : '';
    lines.push(`- id=${e.id} ${span}${e.time ? ` ${e.time}` : ''} ${e.title} [${kindLabel(e.kind)}]${done}`);
  }
  lines.push('');
  lines.push('## お弁当の回答（未記載の日は未回答）');
  const days = Object.entries(lunch).sort(([a], [b]) => a.localeCompare(b));
  if (days.length === 0) lines.push('（回答なし）');
  for (const [date, v] of days) lines.push(`- ${date}: ${v.needed ? 'いる' : 'いらない'}`);
  if (pending) {
    lines.push('');
    lines.push('## いま確認中の予定（会長が「はい」と言えば登録する）');
    lines.push(`- ${pending.date}${pending.endDate ? `〜${pending.endDate}` : ''}${pending.time ? ` ${pending.time}` : ''} ${pending.title} [${pending.kind}]`);
  }
  if (lastAdded) {
    lines.push('');
    lines.push(`## 直前に登録した予定: ${lastAdded.date} ${lastAdded.title} [${lastAdded.kind}]（この日のお弁当をまだ聞いていなければ聞く）`);
  }
  if (names.length > 0) {
    lines.push('');
    lines.push('## 聞き取りの参考（過去の予定に出てきた客先名）');
    lines.push('音が近い名前がここにあればその表記に寄せる（例: リョウワ → 菱和産業、トウホウ → 東邦金属工業）。無い名前は聞こえたとおりに書く。');
    lines.push(names.join('、'));
  }
  lines.push('');
  lines.push('## 予定の書き方の略記（読み上げるときは名前に戻す）');
  lines.push('社＝社長（光明）、和＝和俊、富＝富樫、千＝千葉、倉＝倉西。「+1」は「ほか 1 名」。');
  return lines.join('\n');
}

